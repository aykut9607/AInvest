using Microsoft.EntityFrameworkCore;
using FinancialIQ.Api.Domain.Entities;

namespace FinancialIQ.Api.Infrastructure.EntityFramework;

public class FinancialIqDbContext  : DbContext
{
    public FinancialIqDbContext(DbContextOptions<FinancialIqDbContext > options) : base(options) { }

    public DbSet<FinancialIqResult> FinancialIqResults { get; set; }
    public DbSet<IqHistory> IqHistories { get; set; }
    public DbSet<ScoringRuleVersion> ScoringRuleVersions { get; set; }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<FinancialIqResult>(entity =>
        {
            entity.ToTable("financial_iq_results");

            entity.Property(p => p.Id).HasColumnName("id");
            // nvarchar(max) cannot be an index key, so the column gets a real size before the index below
            entity.Property(p => p.UserId).HasColumnName("user_id").HasMaxLength(FinancialIqResult.UserIdMaxLength);
            entity.Property(p => p.Score).HasColumnName("score");
            entity.Property(p => p.Segment).HasColumnName("segment").HasMaxLength(FinancialIqResult.SegmentMaxLength);
            entity.Property(p => p.FactorBreakdown).HasColumnName("factor_breakdown");
            entity.Property(p => p.CreatedAt).HasColumnName("created_at");
            entity.Property(p => p.UpdatedAt).HasColumnName("updated_at");
            // rowversion column: generated by the database on every write; EF never sends it in an INSERT/UPDATE,
            // and an EF update whose row changed in the meantime fails with DbUpdateConcurrencyException
            entity.Property(p => p.RowVersion).HasColumnName("row_version").IsRowVersion();
            entity.Property(p => p.ScoringVersion).HasColumnName("scoring_version").HasMaxLength(ScoringRuleVersion.VersionMaxLength);
            // every result must point at a stored rule set; a version that is still referenced cannot be deleted
            entity.HasOne<ScoringRuleVersion>().WithMany().HasForeignKey(p => p.ScoringVersion).OnDelete(DeleteBehavior.Restrict);

            // lookups by user become an index seek instead of a full scan, and the database itself
            // refuses a second row for the same user (last line of defence against a concurrent insert)
            entity.HasIndex(p => p.UserId)
                  .IsUnique()
                  .HasDatabaseName("UX_financial_iq_results_user_id");

            // filtered index: only the LOW rows are in it ("users at risk, most recently calculated first", for
            // Notification / Ops). It reads as fast as a full (segment, updated_at) index but holds ~1/5 of the
            // rows, and writes of MEDIUM/HIGH results never touch it. Measured in perf/filtered-index.md.
            // A query only uses it when the filter is written as the literal N'LOW' (see usp_GetLowSegmentResults)
            entity.HasIndex(p => p.UpdatedAt)
                  .IsDescending()
                  .HasFilter("[segment] = N'LOW'")
                  .IncludeProperties(p => new { p.UserId, p.Score })
                  .HasDatabaseName("IX_financial_iq_results_low_segment");
        });

        modelBuilder.Entity<IqHistory>(entity =>
        {
            entity.ToTable("iq_history", t =>
                t.HasCheckConstraint("CK_iq_history_score", "[score] BETWEEN 0 AND 100"));

            // bigint identity: a narrow, ever-increasing clustered key, so new rows always go to the end
            // of the table instead of splitting pages like a random Guid would
            entity.HasKey(p => p.Id);
            entity.Property(p => p.Id).HasColumnName("id").UseIdentityColumn();
            entity.Property(p => p.UserId).HasColumnName("user_id").HasMaxLength(FinancialIqResult.UserIdMaxLength);
            entity.Property(p => p.Score).HasColumnName("score");
            entity.Property(p => p.Segment).HasColumnName("segment").HasMaxLength(FinancialIqResult.SegmentMaxLength);
            entity.Property(p => p.FactorBreakdown).HasColumnName("factor_breakdown");
            entity.Property(p => p.CalculatedAt)
                  .HasColumnName("calculated_at")
                  .HasColumnType("datetime2(3)")
                  .HasDefaultValueSql("SYSUTCDATETIME()");
            entity.Property(p => p.ScoringVersion).HasColumnName("scoring_version").HasMaxLength(ScoringRuleVersion.VersionMaxLength);
            entity.HasOne<ScoringRuleVersion>().WithMany().HasForeignKey(p => p.ScoringVersion).OnDelete(DeleteBehavior.Restrict);

            // covering index for the trend query: seek on the user, rows already ordered newest first,
            // and score/segment are stored in the index so the table itself is never touched (no key lookup)
            entity.HasIndex(p => new { p.UserId, p.CalculatedAt })
                  .IsDescending(false, true)
                  .IncludeProperties(p => new { p.Score, p.Segment })
                  .HasDatabaseName("IX_iq_history_user_id_calculated_at");
        });

        modelBuilder.Entity<ScoringRuleVersion>(entity =>
        {
            // ISJSON: the database refuses a rule set that is not valid JSON
            entity.ToTable("scoring_rule_versions", t =>
                t.HasCheckConstraint("CK_scoring_rule_versions_rules_json", "ISJSON([rules_json]) = 1"));

            entity.HasKey(p => p.Version);
            entity.Property(p => p.Version).HasColumnName("version").HasMaxLength(ScoringRuleVersion.VersionMaxLength);
            entity.Property(p => p.Description).HasColumnName("description").HasMaxLength(500);
            entity.Property(p => p.RulesJson).HasColumnName("rules_json");
            entity.Property(p => p.EffectiveFrom).HasColumnName("effective_from").HasColumnType("datetime2(3)");
            entity.Property(p => p.IsActive).HasColumnName("is_active");

            // filtered UNIQUE index: only rows with is_active = 1 are in it, and it allows at most one of them,
            // so "exactly one active scoring version" is enforced by the database, not just by the code
            entity.HasIndex(p => p.IsActive)
                  .IsUnique()
                  .HasFilter("[is_active] = 1")
                  .HasDatabaseName("UX_scoring_rule_versions_single_active");
        });
    }
}